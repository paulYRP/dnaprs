reportWORKBOOKDICTIONARY <- function(sheet, value, title, source, sensitivity) {
  data.table::data.table(worksheet = sheet, column = names(value),
    definition = vapply(names(value), reportCOLUMNDEFINITION, character(1), title = title),
    data_type = vapply(value, function(x) class(x)[1L], character(1)),
    units_or_scale = "See definition; no additional scale conversion is applied",
    expected_values = "See definition and the source result",
    missing_value = "NA means unavailable or not applicable unless the source defines otherwise",
    source_stage = source, sensitivity = sensitivity)
}
